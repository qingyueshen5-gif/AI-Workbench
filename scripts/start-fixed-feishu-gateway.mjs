import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runtimeRoot } from '../runtime-paths.mjs';
import { writeRuntimeSelection } from './runtime-supervisor.mjs';

const gatewayRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const baselineRoot = process.env.AIW_BASELINE_RUNTIME_ROOT || gatewayRoot;
const baselineCommit = process.env.AIW_BASELINE_RUNTIME_COMMIT || '8d62cdd6432f500254b48847ea58c132c3c5cdad';
const canonicalIpcRoot = resolve(join(runtimeRoot, 'feishu-workbench-bridge', 'ipc'));
const configuredIpcRoot = String(process.env.AIW_FEISHU_IPC_DIR || '').trim();
if (!configuredIpcRoot) throw new Error(`AIW_FEISHU_IPC_DIR must be explicitly set to ${canonicalIpcRoot}`);
if (!isAbsolute(configuredIpcRoot)) throw new Error('AIW_FEISHU_IPC_DIR must be an absolute path');
const ipcRoot = resolve(configuredIpcRoot);
if (ipcRoot.toLowerCase() !== canonicalIpcRoot.toLowerCase()) throw new Error(`IPC directory mismatch: expected ${canonicalIpcRoot}, got ${ipcRoot}`);
await fs.mkdir(ipcRoot, { recursive: true });
const conversationRoot = join(runtimeRoot, 'feishu-workbench-bridge', 'conversations');
const bindingPath = join(runtimeRoot, 'feishu-workbench-bridge', 'ipc-bindings.json');
await writeRuntimeSelection({ selected: { root: baselineRoot, commit: baselineCommit, tag: 'v0.4.7-workflow-baseline-rc1' }, fallback: { root: baselineRoot, commit: baselineCommit, tag: 'v0.4.7-workflow-baseline-rc1' }, requestedBy: 'gateway-startup' });
const gatewayCommit = process.env.AIW_GATEWAY_GIT_COMMIT || 'e91da8839ab16c7bb52249b3ecb2897890a6aff3';
const common = { ...process.env, AIW_FEISHU_IPC_DIR: ipcRoot, AIW_CONVERSATION_DIR: conversationRoot, AIW_ACTIVE_TASK_DIR: join(runtimeRoot, 'feishu-workbench-bridge', 'active-tasks'), AIW_GATEWAY_GIT_COMMIT: gatewayCommit };
process.stdout.write(`AIW_FEISHU_IPC_DIR=${ipcRoot}\n`);
const gateway = spawn(process.execPath, ['scripts/workbench-feishu-adapter.mjs'], { cwd: gatewayRoot, env: common, stdio: 'inherit', windowsHide: true });
const supervisor = spawn(process.execPath, ['scripts/runtime-supervisor.mjs'], { cwd: gatewayRoot, env: { ...common, AIW_RUNTIME_GIT_COMMIT: baselineCommit }, stdio: 'inherit', windowsHide: true });
await fs.writeFile(bindingPath, `${JSON.stringify({ ipcRoot, checkedAt: Date.now(), gateway: { pid: gateway.pid, ipcRoot }, replySender: { pid: gateway.pid, ipcRoot }, supervisor: { pid: supervisor.pid, ipcRoot }, runtime: { pid: 0, ipcRoot, status: 'starting' }, allMatch: true }, null, 2)}\n`, 'utf8');
let stopping=false;
function stop(code=0){if(stopping)return;stopping=true;gateway.kill('SIGTERM');supervisor.kill('SIGTERM');setTimeout(()=>process.exit(code),100);}
process.once('SIGINT',()=>stop(0));process.once('SIGTERM',()=>stop(0));
for(const child of [gateway,supervisor]) child.once('exit',(code)=>{if(!stopping&&code)stop(code);});
